"""One-off experiment (not part of the pipeline): since class labels were
generated by binning images on measured L (Lab lightness) into equal-
frequency groups, L is definitionally the strongest signal for recovering
those labels — other channels (especially hue, which gets noisy on
low-saturation/shadowed skin) may be adding noise rather than signal for
a 37-sample training set. This script checks that empirically via
cross-validation instead of assuming it.
"""

import csv
import sys
from pathlib import Path

import numpy as np
from sklearn.ensemble import ExtraTreesClassifier, GradientBoostingClassifier, RandomForestClassifier
from sklearn.metrics import f1_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

BACKEND_ROOT = Path(__file__).resolve().parent.parent / "backend"
sys.path.insert(0, str(BACKEND_ROOT))
from app.services.features import FEATURE_NAMES  # noqa: E402

LABELS_CSV = Path(__file__).resolve().parent.parent / "dataset_processed" / "labels.csv"
CLASS_ORDER = ["very_fair", "fair", "light", "medium", "olive", "tan", "brown", "deep"]

FEATURE_SETS = {
    "full_18": FEATURE_NAMES,
    "lab_only_6": ["L_med", "L_std", "a_med", "a_std", "b_med", "b_std"],
    "L_ab_medians_3": ["L_med", "a_med", "b_med"],
    "L_plus_chroma_5": ["L_med", "L_std", "a_med", "b_med", "S_med"],
}

MODELS = {
    "rf_d5_300": lambda: RandomForestClassifier(n_estimators=300, max_depth=5, class_weight="balanced", random_state=42),
    "rf_d4_500": lambda: RandomForestClassifier(n_estimators=500, max_depth=4, class_weight="balanced", random_state=42),
    "rf_d3_500": lambda: RandomForestClassifier(n_estimators=500, max_depth=3, class_weight="balanced", random_state=42),
    "extratrees_d5": lambda: ExtraTreesClassifier(n_estimators=300, max_depth=5, class_weight="balanced", random_state=42),
    "gboost_d2": lambda: GradientBoostingClassifier(n_estimators=150, max_depth=2, random_state=42),
}


def load_xy(feature_names):
    rows = [r for r in csv.DictReader(open(LABELS_CSV)) if r["split"] in ("train", "validation")]
    X = np.array([[float(r[n]) for n in feature_names] for r in rows])
    y = np.array([r["class_id"] for r in rows])
    return X, y


def off_by_one_accuracy(y_true, y_pred):
    idx = {c: i for i, c in enumerate(CLASS_ORDER)}
    t = np.array([idx[c] for c in y_true])
    p = np.array([idx[c] for c in y_pred])
    return float((np.abs(t - p) <= 1).mean())


def main():
    results = []
    for set_name, feature_names in FEATURE_SETS.items():
        X, y = load_xy(feature_names)
        n_splits = max(2, min(4, min(np.bincount(np.unique(y, return_inverse=True)[1]))))
        skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=42)

        for model_name, model_fn in MODELS.items():
            pipeline = Pipeline([("scaler", StandardScaler()), ("clf", model_fn())])
            preds = cross_val_predict(pipeline, X, y, cv=skf)
            exact = float((preds == y).mean())
            adj = off_by_one_accuracy(y, preds)
            macro_f1 = f1_score(y, preds, labels=CLASS_ORDER, average="macro", zero_division=0)
            results.append((set_name, model_name, exact, adj, macro_f1))

    results.sort(key=lambda r: (r[2], r[3]), reverse=True)
    print(f"{'feature_set':<18} {'model':<14} {'exact':>7} {'off_by_1':>9} {'macro_f1':>9}")
    for set_name, model_name, exact, adj, f1 in results:
        print(f"{set_name:<18} {model_name:<14} {exact:>7.2f} {adj:>9.2f} {f1:>9.2f}")


if __name__ == "__main__":
    main()
